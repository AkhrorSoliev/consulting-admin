import { Page, Text, View } from "@react-pdf/renderer";
import { pdfStyles, splitCommentLabelLine, renderPdfStars } from "../cvPdfStyles";

export default function PdfCommentPage({
  commentPlain,
  commentDate,
  autoGeneratedNote,
  showCommentDate,
  rating,
}) {
  return (
    <Page size="A4" style={[pdfStyles.page, pdfStyles.pageWithFooter]}>
      <View style={pdfStyles.commentHeader}>
        <Text style={pdfStyles.name}>Erst- und Zweitgespr&auml;chsfeedback</Text>
        {rating !== null && rating > 0 && (
          <View
            style={{
              flexDirection: "row",
              alignItems: "center",
              gap: 4,
              marginTop: 20,
              marginBottom: 4,
            }}
          >
            {renderPdfStars(rating)}
          </View>
        )}
        <View style={pdfStyles.divider} />
      </View>
      <View style={pdfStyles.commentBody}>
        {String(commentPlain || "")
          .split("\n")
          .map((line, idx) => {
            const parsed = splitCommentLabelLine(line);
            if (!parsed) {
              return (
                <Text key={idx} style={pdfStyles.commentLine}>
                  {line || " "}
                </Text>
              );
            }
            return (
              <Text key={idx} style={pdfStyles.commentLine}>
                <Text style={{ fontWeight: "bold" }}>{parsed.labelText}</Text>
                <Text>{parsed.tailText}</Text>
              </Text>
            );
          })}
      </View>
      {showCommentDate && (
        <View style={pdfStyles.commentFooter}>
          <Text style={pdfStyles.commentDate}>
            Datum: {commentDate || "\u2014"}
          </Text>
          <Text style={pdfStyles.commentAutoGenerated}>
            {autoGeneratedNote}
          </Text>
        </View>
      )}
    </Page>
  );
}
